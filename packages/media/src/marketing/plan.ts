/** "الجمعة، ١٦ أكتوبر" for a plan date. */
export const arabicDay = (date: string): string =>
  new Date(`${date}T12:00:00Z`).toLocaleDateString("ar-EG", {
    weekday: "long",
    day: "numeric",
    month: "long",
    timeZone: "UTC",
  });
